/**
 * Review state of a workflow and the risk checks for runs a model starts.
 *
 * A workflow written by a model (the plugin's tools, the AI generator) or
 * imported from a file is `unreviewed` and refuses to run until a person
 * approves it: in the canvas (HTTP API, which needs the DSH login and the
 * CSRF header) or once through DSH's own approval dialog. Approval is bound
 * to a digest of the executable content, so any later change that did not
 * come from the canvas drops it again.
 */
import { createHash } from 'node:crypto'
import { effectiveKernelPolicy, isElevated } from '../kernels/policy.js'
import type { KernelDefinition, KernelMode, KernelPermission } from '../kernels/types.js'
import type { Workflow, WorkflowNode, WorkflowReview, WorkflowReviewSource } from './types.js'

function stable(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(stable)
  if (value !== null && typeof value === 'object') {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map(key => [key, stable((value as Record<string, unknown>)[key])]),
    )
  }
  return value
}

/** Digest of everything that changes what a run does (layout, name and description excluded). */
export function reviewDigest(workflow: Workflow): string {
  const material = {
    nodes: workflow.nodes.map(n => ({ id: n.id, type: n.type, config: n.config, retry: n.retry, timeoutMs: n.timeoutMs, continueOnFailure: n.continueOnFailure })),
    edges: workflow.edges.map(e => ({ source: e.source, target: e.target, route: e.route })),
    inputs: workflow.inputs,
    budget: workflow.budget,
    deadlineMs: workflow.deadlineMs,
    concurrency: workflow.concurrency,
    triggers: workflow.triggers,
  }
  return `sha256-${createHash('sha256').update(JSON.stringify(stable(material))).digest('hex')}`
}

export function markUnreviewed(workflow: Workflow, source: WorkflowReviewSource): Workflow {
  workflow.review = { status: 'unreviewed', source }
  return workflow
}

export function markApproved(workflow: Workflow, by: string, source: WorkflowReviewSource = workflow.review?.source ?? 'user'): Workflow {
  workflow.review = { status: 'approved', source, digest: reviewDigest(workflow), by, at: new Date().toISOString() }
  return workflow
}

/** Languages the Host-side texts shown to a person (DSH's approval dialog) come in. */
export type TextLanguage = 'zh-CN' | 'en'

/** Undefined when the workflow may run; otherwise why not. */
export function reviewProblem(workflow: Workflow, lang: TextLanguage = 'en'): string | undefined {
  const zh = lang === 'zh-CN'
  const review = workflow.review
  if (review === undefined) return zh ? '这个工作流尚未审核' : 'this workflow has not been reviewed yet'
  if (review.status !== 'approved') {
    if (zh) {
      const origin = review.source === 'model' ? '由模型编写' : review.source === 'generated' ? '由 AI 生成' : review.source === 'import' ? '是导入的' : ''
      return `这个工作流${origin}${origin ? '，' : ''}尚未审核`
    }
    const origin = review.source === 'model' ? 'was written by the model' : review.source === 'generated' ? 'was generated by the model' : review.source === 'import' ? 'was imported' : 'has not been reviewed'
    return `this workflow ${origin} and has not been reviewed yet`
  }
  if (review.digest !== reviewDigest(workflow)) return zh ? '这个工作流在批准后被改动过' : 'this workflow changed after it was approved'
  return undefined
}

/** Public view for the canvas: status plus the digest the approve call must echo back. */
export function reviewInfo(workflow: Workflow): WorkflowReview & { digest: string; runnable: boolean; problem: string | null } {
  const problem = reviewProblem(workflow) ?? null
  return {
    ...(workflow.review ?? { status: 'unreviewed', source: 'legacy' }),
    ...(problem !== null ? { status: 'unreviewed' as const } : {}),
    digest: reviewDigest(workflow),
    runnable: problem === null,
    problem,
  }
}

/** Fields of kernel and agent steps that must be literal (never templated): they decide privileges. */
export const LITERAL_FIELDS: Record<string, readonly string[]> = {
  kernel: ['kernel', 'mode', 'permission', 'cwd'],
  agent: ['preset', 'cwd'],
}

export interface RiskContext {
  kernel(id: string): Pick<KernelDefinition, 'permissions' | 'name'> | undefined
  setting(id: string): { mode: KernelMode; permission: KernelPermission }
}

/** Kinds of privileged step, in the order the approval summary lists them. */
export type RiskKind = 'kernel' | 'script' | 'http' | 'notify' | 'agent'
const RISK_ORDER: readonly RiskKind[] = ['kernel', 'script', 'http', 'notify', 'agent']

/** One step that does more than read. `fact` describes it without the node label (English; `factZh` in Chinese). */
export interface RiskFact {
  kind: RiskKind
  nodeId: string
  label: string
  fact: string
  factZh: string
}

/** Longest node label quoted in an approval summary (names are capped at 120 by lint as well). */
const LABEL_MAX = 40

function shortLabel(name: string, id: string): string {
  const clean = name.replace(/\s+/g, ' ').trim()
  const cut = clean.length > LABEL_MAX ? `${clean.slice(0, LABEL_MAX - 1)}…` : clean
  return cut && cut !== id ? `${cut} (${id})` : id
}

const PERMISSION_ZH: Record<string, string> = { 'read-only': '只读', ask: '询问', edit: '可编辑', full: '完全放行' }
const MODE_ZH: Record<string, string> = { scoped: '经 DSH', global: '原生登录' }

function stepRisk(type: string, config: Record<string, unknown>, ctx: RiskContext): Omit<RiskFact, 'nodeId' | 'label'> | undefined {
  switch (type) {
    case 'kernel': {
      const id = String(config.kernel ?? '')
      const def = ctx.kernel(id)
      if (def === undefined) return undefined
      const policy = effectiveKernelPolicy({ requestedMode: config.mode, requestedPermission: config.permission, setting: ctx.setting(id), def })
      if (!isElevated(policy)) return undefined
      return {
        kind: 'kernel',
        fact: `${def.name} with "${policy.permission}" permission in ${policy.mode} mode`,
        factZh: `${def.name}，权限「${PERMISSION_ZH[policy.permission] ?? policy.permission}」(${policy.permission})，模式「${MODE_ZH[policy.mode] ?? policy.mode}」(${policy.mode})`,
      }
    }
    case 'script':
      return { kind: 'script', fact: 'script node (runs JavaScript as your user)', factZh: '脚本节点（以你的系统用户身份运行 JavaScript）' }
    case 'http':
    case 'notify': {
      const url = String(config.url ?? '?').slice(0, 120)
      return { kind: type, fact: `${type} request to ${url}`, factZh: `${type === 'http' ? 'HTTP 请求' : '通知请求'}：${url}` }
    }
    case 'agent': {
      if (typeof config.preset !== 'string' || !config.preset) return undefined
      const preset = config.preset.slice(0, 60)
      return { kind: 'agent', fact: `DSH agent with preset "${preset}"`, factZh: `使用预设「${preset}」的 DSH 智能体` }
    }
    default:
      return undefined
  }
}

/** Steps that do more than read, ordered by kind (kernels first), then by node order. */
export function riskFacts(workflow: Workflow, ctx: RiskContext): RiskFact[] {
  const out: RiskFact[] = []
  for (const node of workflow.nodes as WorkflowNode[]) {
    const label = shortLabel(node.name || node.id, node.id)
    if (node.type === 'loop') {
      const body = (node.config.body ?? {}) as { type?: string; config?: Record<string, unknown> }
      const risk = stepRisk(String(body.type ?? ''), body.config ?? {}, ctx)
      if (risk !== undefined) out.push({ ...risk, nodeId: node.id, label: `${label} loop body` })
    } else {
      const risk = stepRisk(node.type, node.config, ctx)
      if (risk !== undefined) out.push({ ...risk, nodeId: node.id, label })
    }
  }
  return out.map((r, i) => ({ r, i })).sort((a, b) => RISK_ORDER.indexOf(a.r.kind) - RISK_ORDER.indexOf(b.r.kind) || a.i - b.i).map(x => x.r)
}

/** Steps that do more than read (elevated kernels, scripts, outbound requests, agent presets). */
export function riskyNodes(workflow: Workflow, ctx: RiskContext): string[] {
  return riskFacts(workflow, ctx).map(r => `${r.label}: ${r.fact}`)
}

/** Most characters DSH's approval dialog is given. */
export const APPROVAL_REASON_MAX = 1500

const SUMMARY_TEXT = {
  en: {
    kernels: (list: string) => `raised CLI permissions: ${list}`,
    count: (n: number, kind: Exclude<RiskKind, 'kernel'>) =>
      `${n} ${{ script: n === 1 ? 'script node' : 'script nodes', http: n === 1 ? 'HTTP request' : 'HTTP requests', notify: n === 1 ? 'notify request' : 'notify requests', agent: n === 1 ? 'DSH agent preset' : 'DSH agent presets' }[kind]}`,
    none: 'no raised CLI permissions, scripts, outbound requests or agent presets',
    review: 'Review',
    steps: 'Steps',
    sep: '; ',
    end: '.',
    colon: ': ',
    space: ' ',
  },
  'zh-CN': {
    kernels: (list: string) => `提升的 CLI 权限：${list}`,
    count: (n: number, kind: Exclude<RiskKind, 'kernel'>) => `${n} 个${{ script: '脚本节点', http: ' HTTP 请求', notify: '通知请求', agent: ' DSH 智能体预设' }[kind]}`,
    none: '没有提升的 CLI 权限、脚本、外发请求或智能体预设',
    review: '审核',
    steps: '步骤',
    sep: '；',
    end: '。',
    colon: '：',
    space: '',
  },
} as const

/**
 * Text for DSH's approval dialog. Privileges come first and are named
 * explicitly (each raised CLI with its permission and mode, then counts of
 * scripts, requests and agent presets), then the review state, then per-step
 * details. Only the details can be cut off by the length limit.
 */
export function approvalSummary(what: string, workflow: Workflow, ctx: RiskContext, lang: TextLanguage = 'en'): string {
  const L = SUMMARY_TEXT[lang]
  const zh = lang === 'zh-CN'
  const risks = riskFacts(workflow, ctx)
  const count = (kind: RiskKind): number => risks.filter(r => r.kind === kind).length
  const head: string[] = []
  const kernels = [...new Set(risks.filter(r => r.kind === 'kernel').map(r => (zh ? r.factZh : r.fact)))]
  if (kernels.length > 0) head.push(L.kernels(kernels.join(zh ? '、' : ', ')))
  for (const kind of ['script', 'http', 'notify', 'agent'] as const) if (count(kind) > 0) head.push(L.count(count(kind), kind))
  if (head.length === 0) head.push(L.none)
  const problem = reviewProblem(workflow, lang)
  const parts = [`${what.slice(0, 200)}${L.end}${L.space}${head.join(L.sep)}${L.end}`]
  if (problem !== undefined) parts.push(`${L.review}${L.colon}${problem}${L.end}`)
  if (risks.length > 0) parts.push(`${L.steps}${L.colon}${risks.map(r => `${zh ? r.factZh : r.fact} [${r.label}]`).join(L.sep)}${L.end}`)
  const text = parts.join(L.space)
  return text.length > APPROVAL_REASON_MAX ? `${text.slice(0, APPROVAL_REASON_MAX - 1)}…` : text
}
