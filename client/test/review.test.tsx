/** Review gate: banner, Approve, stale reload, 409 handling, list badge. */
import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { describe, expect, it } from 'vitest'
import type { ReviewInfo, Workflow, WorkflowListItem } from '../src/api/types.ts'
import { ReviewBanner, WorkflowsView } from '../src/canvas/WorkflowsView.tsx'
import { createFlowController, needsReview } from '../src/store/flow.ts'
import { bind, fakeApi, kernel, run, t, tz, workflow, type Route } from './helpers.tsx'

const review = (partial: Partial<ReviewInfo> = {}): ReviewInfo => ({ status: 'unreviewed', source: 'generated', digest: 'sha256-a', runnable: false, problem: 'this workflow was generated by the model and has not been reviewed yet', ...partial })
const approved = (digest = 'sha256-a'): ReviewInfo => ({ status: 'approved', source: 'generated', digest, runnable: true, problem: null, by: 'canvas', at: '2026-10-22T08:00:00.000Z' })

function setup(extra: Route = () => undefined, initial: ReviewInfo = review()) {
  let saved: Workflow = workflow({ inputs: [] })
  let state = initial
  let digest = initial.digest
  const { api, calls } = fakeApi((method, path, body) => {
    const x = extra(method, path, body)
    if (x) return x
    const item: WorkflowListItem = { id: 'wf1', name: 'Triage', description: '', nodes: 4, updatedAt: '', lastRun: null, review: { status: state.runnable ? 'approved' : 'unreviewed', source: state.source } }
    if (method === 'GET' && path === '/workflows') return { body: { workflows: [item] } }
    if (method === 'GET' && path === '/workflows/wf1') return { body: { workflow: saved, issues: [], review: state } }
    if (method === 'PUT' && path === '/workflows/wf1') {
      saved = body as Workflow
      digest = 'sha256-b'
      state = { ...state, digest }
      return { body: { workflow: saved, issues: [], review: state } }
    }
    if (method === 'POST' && path === '/workflows/wf1/approve') {
      if ((body as { digest?: string }).digest !== digest) return { status: 409, body: { error: 'the workflow changed since you opened it; reload and review it again', code: 'stale_review' } }
      state = approved(digest)
      return { body: { workflow: saved, review: state } }
    }
    if (method === 'POST' && path === '/workflows/wf1/run') {
      if (!state.runnable) return { status: 409, body: { error: 'this workflow was generated by the model and has not been reviewed yet', code: 'unreviewed' } }
      return { status: 202, body: { run: { id: 'run-12345678' } } }
    }
    if (method === 'GET' && path === '/runs/run-12345678') return { body: { run: run({ status: 'running' }) } }
    if (method === 'POST' && path === '/workflows/wf1/lint') return { body: { issues: [] } }
    if (method === 'GET' && path.startsWith('/runs?')) return { body: { runs: [] } }
    if (method === 'GET' && path.startsWith('/kernels')) return { body: { kernels: [kernel()] } }
    return undefined
  })
  const controller = createFlowController(api, { pollMs: 5 })
  return { ...controller, calls, useFlow: bind(controller.store), setDigest: (d: string) => void (digest = d) }
}

describe('review gate (controller)', () => {
  it('keeps the Host review state and approves with its digest', async () => {
    const { store, actions, calls } = setup()
    await actions.openWorkflow('wf1')
    expect(needsReview(store.getSnapshot())).toBe(true)
    expect(await actions.approve()).toBe(true)
    expect(calls.find(c => c.path === '/workflows/wf1/approve')?.body).toEqual({ digest: 'sha256-a' })
    expect(calls.find(c => c.path === '/workflows/wf1/approve')?.headers['x-lulux-flow-request']).toBe('1')
    expect(needsReview(store.getSnapshot())).toBe(false)
    expect(store.getSnapshot().toasts.at(-1)).toMatchObject({ tone: 'success', text: 'toast.reviewApproved' })
  })

  it('saves pending edits first, then approves the saved version', async () => {
    const { store, actions, calls } = setup()
    await actions.openWorkflow('wf1')
    actions.updateWorkflow(wf => ({ ...wf, nodes: wf.nodes.map(n => (n.id === 'review' ? { ...n, config: { ...n.config, prompt: 'Edited' } } : n)) }))
    expect(await actions.approve()).toBe(true)
    const order = calls.filter(c => c.method !== 'GET' && !c.path.endsWith('/lint')).map(c => `${c.method} ${c.path}`)
    expect(order).toEqual(['PUT /workflows/wf1', 'POST /workflows/wf1/approve'])
    expect(calls.find(c => c.path === '/workflows/wf1/approve')?.body).toEqual({ digest: 'sha256-b' })
    expect(store.getSnapshot().editor.review?.runnable).toBe(true)
  })

  it('reloads the workflow when the approval is stale', async () => {
    const { store, actions, calls, setDigest } = setup()
    await actions.openWorkflow('wf1')
    setDigest('sha256-changed-elsewhere')
    const opens = calls.filter(c => c.method === 'GET' && c.path === '/workflows/wf1').length
    expect(await actions.approve()).toBe(false)
    expect(calls.filter(c => c.method === 'GET' && c.path === '/workflows/wf1').length).toBe(opens + 1)
    expect(store.getSnapshot().toasts.some(x => x.text === 'toast.reviewStale' && x.tone === 'info')).toBe(true)
    expect(store.getSnapshot().toasts.some(x => x.tone === 'error')).toBe(false)
    expect(needsReview(store.getSnapshot())).toBe(true)
  })

  it('turns a 409 unreviewed run into the review banner, not a run error', async () => {
    // The editor still thinks it is approved (e.g. the model changed it a moment ago).
    let first = true
    const { store, actions } = setup((method, path) => {
      if (method === 'GET' && path === '/workflows/wf1' && first) {
        first = false
        return { body: { workflow: workflow({ inputs: [] }), issues: [], review: approved() } }
      }
      return undefined
    })
    await actions.openWorkflow('wf1')
    expect(needsReview(store.getSnapshot())).toBe(false)
    await actions.run({})
    await waitFor(() => expect(needsReview(store.getSnapshot())).toBe(true))
    expect(store.getSnapshot().toasts.at(-1)).toMatchObject({ tone: 'info', text: 'toast.runUnreviewed' })
    expect(store.getSnapshot().toasts.some(x => x.text === 'toast.runFailed')).toBe(false)
    expect(store.getSnapshot().runs.active).toBeNull()
  })

  it('treats a 409 unreviewed rerun the same way', async () => {
    const { store, actions } = setup((method, path) => (method === 'POST' && path === '/runs/run-12345678/rerun' ? { status: 409, body: { error: 'not reviewed', code: 'unreviewed' } } : undefined))
    await actions.rerun('run-12345678')
    expect(store.getSnapshot().toasts.at(-1)).toMatchObject({ tone: 'info', text: 'toast.runUnreviewed' })
  })

  it('refreshes the review state when the Host reports a workflow change', async () => {
    let emit: (e: unknown) => void = () => undefined
    const { api } = fakeApi((method, path) => {
      if (method === 'GET' && path === '/workflows/wf1') return { body: { workflow: workflow(), issues: [], review: emitted ? approved() : review() } }
      if (method === 'GET') return { body: { workflows: [], runs: [], kernels: [] } }
      return undefined
    })
    let emitted = false
    api.subscribe = listener => {
      emit = listener as (e: unknown) => void
      return () => undefined
    }
    const { store, actions } = createFlowController(api)
    const stop = actions.start()
    await actions.openWorkflow('wf1')
    expect(needsReview(store.getSnapshot())).toBe(true)
    emitted = true
    emit({ type: 'workflow', workflowId: 'wf1' })
    await waitFor(() => expect(needsReview(store.getSnapshot())).toBe(false))
    stop()
  })
})

describe('ReviewBanner', () => {
  it('names where the workflow came from', () => {
    const { rerender } = render(<ReviewBanner t={t} review={review({ source: 'model' })} dirty={false} busy={false} onApprove={() => undefined} />)
    const banner = screen.getByRole('region', { name: 'Review required' })
    expect(banner.textContent).toMatch(/written by the model/)
    expect(banner.textContent).toMatch(/Review the nodes, then approve to run/)
    rerender(<ReviewBanner t={t} review={review({ source: 'import' })} dirty={false} busy={false} onApprove={() => undefined} />)
    expect(screen.getByRole('region').textContent).toMatch(/imported/)
    rerender(<ReviewBanner t={t} review={review({ source: 'user', by: 'canvas' })} dirty={false} busy={false} onApprove={() => undefined} />)
    expect(screen.getByRole('region').textContent).toMatch(/changed after it was approved/)
    rerender(<ReviewBanner t={t} review={review()} dirty busy={false} onApprove={() => undefined} />)
    expect(screen.getByRole('button', { name: 'Save and approve' })).toBeTruthy()
  })

  it('reads in Chinese and disables Approve while busy', () => {
    render(<ReviewBanner t={tz} review={review()} dirty={false} busy onApprove={() => undefined} />)
    const banner = screen.getByRole('region', { name: '需要审核' })
    expect(banner.textContent).toMatch(/AI 生成/)
    expect((within(banner).getByRole('button', { name: '批准' }) as HTMLButtonElement).disabled).toBe(true)
  })
})

describe('WorkflowsView review flow', () => {
  it('shows the badge and banner, blocks Run until Approve, then runs', async () => {
    const { actions, useFlow, calls } = setup()
    await act(async () => {
      await actions.refreshWorkflows()
      await actions.openWorkflow('wf1')
    })
    render(<WorkflowsView t={t} locale="en" useFlow={useFlow} actions={actions} />)
    const list = screen.getByRole('complementary', { name: 'Workflow list' })
    expect(within(list).getByText('Unreviewed')).toBeTruthy()
    const banner = screen.getByRole('region', { name: 'Review required' })
    expect(banner.textContent).toMatch(/generated/)
    const toolbar = screen.getByRole('toolbar')
    const runButton = within(toolbar).getByRole('button', { name: 'Run' }) as HTMLButtonElement
    expect(runButton.disabled).toBe(true)
    expect(runButton.title).toBe('Approve this workflow before running it')
    fireEvent.click(within(banner).getByRole('button', { name: 'Approve' }))
    await waitFor(() => expect(screen.queryByRole('region', { name: 'Review required' })).toBeNull())
    await waitFor(() => expect(within(list).queryByText('Unreviewed')).toBeNull())
    expect((within(toolbar).getByRole('button', { name: 'Run' }) as HTMLButtonElement).disabled).toBe(false)
    fireEvent.click(within(toolbar).getByRole('button', { name: 'Run' }))
    await waitFor(() => expect(calls.some(c => c.method === 'POST' && c.path === '/workflows/wf1/run')).toBe(true))
  })
})
