#!/usr/bin/env node
/**
 * Build DSH-LULUX Flow.
 *
 *   lib/index.js        Host plugin (ESM bundle of src/, dependencies external)
 *   lib/types/**.d.ts   Host declarations (tsc --emitDeclarationOnly)
 *   lib/client.js       Browser half in DSH's lazy-CJS module-loader format:
 *                       window.__ModuleLoader__.load({ id, factory(require) }).
 *                       React and react-dom resolve from DSH's shared platform
 *                       module table; everything else (xyflow, styles, avatars)
 *                       is bundled so the file is self-contained.
 *
 * Flags:
 *   --if-missing   skip when lib/index.js and lib/client.js already exist (used by `prepare`)
 *   --client       client only        --server   server only
 *   --dev          unminified client with inline source map
 */
import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const lib = join(root, 'lib')
const args = new Set(process.argv.slice(2))
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))

if (args.has('--if-missing') && existsSync(join(lib, 'index.js')) && existsSync(join(lib, 'client.js'))) {
  console.log('[build] lib/ present, skipping (run `pnpm build` to rebuild)')
  process.exit(0)
}

let esbuild
try {
  esbuild = await import('esbuild')
} catch {
  // `prepare` can run where devDependencies are absent (e.g. a production install from a tarball, which ships lib/ already).
  if (existsSync(join(lib, 'index.js')) && existsSync(join(lib, 'client.js'))) process.exit(0)
  console.error('[build] esbuild is not installed; run `pnpm install` first')
  process.exit(1)
}

const only = args.has('--client') ? 'client' : args.has('--server') ? 'server' : 'all'
const dev = args.has('--dev')
mkdirSync(lib, { recursive: true })

/** Dependencies that stay external in the Host bundle. */
const hostExternals = [
  ...Object.keys(pkg.dependencies ?? {}),
  ...Object.keys(pkg.peerDependencies ?? {}),
  '@deepseek-ai/*',
]

async function buildServer() {
  const started = Date.now()
  await esbuild.build({
    entryPoints: [join(root, 'src/index.ts')],
    outfile: join(lib, 'index.js'),
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node22',
    sourcemap: false,
    legalComments: 'inline',
    external: hostExternals,
    logLevel: 'warning',
  })
  const tsc = spawnSync(process.execPath, [createRequire(import.meta.url).resolve('typescript/bin/tsc'), '-p', join(root, 'tsconfig.json'), '--emitDeclarationOnly'], {
    cwd: root,
    stdio: 'inherit',
  })
  if (tsc.status !== 0) throw new Error('tsc --emitDeclarationOnly failed')
  console.log(`[build] lib/index.js + lib/types (${Date.now() - started} ms)`)
}

/** `import css from './x.css?raw'` → the file's text (mirrors Vite, which the tests use). */
const rawPlugin = {
  name: 'raw',
  setup(build) {
    build.onResolve({ filter: /\?raw$/ }, async args => {
      const result = await build.resolve(args.path.slice(0, -4), { resolveDir: args.resolveDir, kind: args.kind, importer: args.importer })
      if (result.errors.length > 0) return { errors: result.errors }
      return { path: result.path, namespace: 'raw' }
    })
    build.onLoad({ filter: /.*/, namespace: 'raw' }, args => ({ contents: readFileSync(args.path, 'utf8'), loader: 'text' }))
  },
}

/** Shared platform modules DSH's shell seeds; requested through the loader's require. */
const PLATFORM = ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client']

async function buildClient() {
  const started = Date.now()
  const result = await esbuild.build({
    entryPoints: [join(root, 'client/src/index.ts')],
    bundle: true,
    write: false,
    format: 'cjs',
    platform: 'browser',
    target: ['chrome111', 'safari16.4', 'firefox115'],
    jsx: 'automatic',
    minify: !dev,
    sourcemap: dev ? 'inline' : false,
    legalComments: 'inline',
    external: PLATFORM,
    loader: { '.png': 'dataurl', '.svg': 'dataurl' },
    define: { 'process.env.NODE_ENV': dev ? '"development"' : '"production"' },
    plugins: [rawPlugin],
    logLevel: 'warning',
  })
  const code = result.outputFiles[0].text
  const id = JSON.stringify(pkg.name)
  const wrapped =
    `/* ${pkg.name}@${pkg.version} browser half — generated by scripts/build.mjs; do not edit. */\n` +
    `window.__ModuleLoader__.load({\n` +
    `\tid: ${id},\n` +
    `\tfactory: (require) => {\n` +
    `\t\tvar module = { exports: {} };\n` +
    `\t\tvar exports = module.exports;\n` +
    `${code}\n` +
    `\t\treturn module.exports;\n` +
    `\t}\n` +
    `});\n`
  writeFileSync(join(lib, 'client.js'), wrapped)
  const kb = (statSync(join(lib, 'client.js')).size / 1024).toFixed(0)
  console.log(`[build] lib/client.js ${kb} KB (${Date.now() - started} ms)`)
}

try {
  if (only !== 'client') await buildServer()
  if (only !== 'server') await buildClient()
} catch (error) {
  console.error(`[build] ${error instanceof Error ? error.message : String(error)}`)
  process.exit(1)
}
